"""Manage the Dell bootupd console override; no kernel or timeout changes."""
import argparse
import fcntl
import hashlib
import json
import os
from pathlib import Path
import stat
import subprocess
import sys
import tempfile

BOOT = Path('/boot/grub2')
STATE = BOOT / 'foundation-dell-grub'
FONT = Path('/usr/share/grub/unicode.pf2')
LOCK = Path('/run/lock/foundation-dell-grub.lock')
BLOCK = b'''# Foundation Dell XPS 13 9350 graphical console
insmod efi_gop
insmod gfxterm
set gfxmode=auto
if loadfont $prefix/foundation-dell-grub/unicode.pf2; then
    terminal_output gfxterm
fi
'''


def digest(data):
    return hashlib.sha256(data).hexdigest()


def regular(path):
    if path.is_symlink() or (path.exists() and not path.is_file()):
        raise RuntimeError(f'Refusing non-regular file: {path}')


def atomic(path, data, mode=0o644, uid=0, gid=0):
    regular(path)
    fd, name = tempfile.mkstemp(prefix='.foundation-', dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as stream:
            stream.write(data)
            stream.flush()
            os.fchmod(stream.fileno(), mode)
            os.fchown(stream.fileno(), uid, gid)
            os.fsync(stream.fileno())
        os.replace(name, path)
        directory = os.open(path.parent, os.O_RDONLY | os.O_DIRECTORY)
        try:
            os.fsync(directory)
        finally:
            os.close(directory)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def supported():
    try:
        return (
            Path('/sys/firmware/efi').is_dir()
            and Path('/run/ostree-booted').exists()
            and Path('/sys/class/dmi/id/sys_vendor').read_text().strip() == 'Dell Inc.'
            and Path('/sys/class/dmi/id/product_name').read_text().strip() == 'XPS 13 9350'
        )
    except OSError:
        return False


def validate_boot():
    for path in (BOOT.parent, BOOT):
        info = path.lstat()
        if not stat.S_ISDIR(info.st_mode) or info.st_uid != 0 or info.st_mode & 0o022:
            raise RuntimeError(f'Refusing unsafe boot directory: {path}')
    regular(BOOT / 'grub.cfg')
    config = (BOOT / 'grub.cfg').read_text()
    if 'Generated by bootupd' not in config or 'source $prefix/console.cfg' not in config:
        raise RuntimeError('Expected bootupd configuration with console.cfg hook')
    regular(BOOT / 'console.cfg')
    if STATE.is_symlink() or (STATE.exists() and not STATE.is_dir()):
        raise RuntimeError('Refusing unsafe Foundation state directory')
    if STATE.exists():
        info = STATE.stat()
        if info.st_uid != 0 or info.st_mode & 0o022:
            raise RuntimeError('Foundation state must be root-owned and not writable by others')
        for child in STATE.iterdir():
            if child.name not in {'manifest.json', 'original.cfg', 'unicode.pf2'}:
                raise RuntimeError(f'Unexpected file in Foundation state: {child}')
            regular(child)


def load_state():
    manifest = STATE / 'manifest.json'
    if not manifest.exists():
        if STATE.exists():
            raise RuntimeError('Incomplete Foundation state; inspect before retrying')
        return None
    state = json.loads(manifest.read_text())
    if state['schema'] != 1:
        raise RuntimeError('Unsupported Foundation state version')
    original = (STATE / 'original.cfg').read_bytes()
    if digest(original) != state['originalHash']:
        raise RuntimeError('Original console backup was modified; refusing to restore it')
    expected = original + (b'\n' if original and not original.endswith(b'\n') else b'') + BLOCK
    current = (BOOT / 'console.cfg').read_bytes() if (BOOT / 'console.cfg').exists() else None
    old = original if state['existed'] else None
    if current not in (expected, old):
        raise RuntimeError('console.cfg changed outside Foundation; preserve/reconcile edits first')
    if digest((STATE / 'unicode.pf2').read_bytes()) != state['fontHash']:
        raise RuntimeError('Managed font changed outside Foundation')
    return state, original, expected, current


def install():
    validate_boot()
    regular(FONT)
    font = FONT.read_bytes()
    if not font.startswith(b'FILE\x00\x00\x00\x04PFF2'):
        raise RuntimeError('Expected a GRUB PFF2 font')
    loaded = load_state()
    if loaded:
        state, original, expected, current = loaded
        if current == expected:
            print('Dell GRUB graphical console is already installed.')
            return
    else:
        target = BOOT / 'console.cfg'
        existed = target.exists()
        original = target.read_bytes() if existed else b''
        if b'foundation-dell-grub' in original:
            raise RuntimeError('Existing Foundation console reference has no backup state')
        info = target.stat() if existed else None
        state = dict(schema=1, existed=existed, originalHash=digest(original),
                     fontHash=digest(font), mode=stat.S_IMODE(info.st_mode) if info else 0o644,
                     uid=info.st_uid if info else 0, gid=info.st_gid if info else 0)
        expected = original + (b'\n' if original and not original.endswith(b'\n') else b'') + BLOCK
        STATE.mkdir(mode=0o700)
        atomic(STATE / 'original.cfg', original, 0o600)
        atomic(STATE / 'unicode.pf2', font)
        atomic(STATE / 'manifest.json', json.dumps(state).encode(), 0o600)
    atomic(BOOT / 'console.cfg', expected)
    print('Installed Dell GRUB graphical console. It takes effect on the next boot.')


def uninstall():
    validate_boot()
    loaded = load_state()
    if not loaded:
        print('No Foundation-managed GRUB console is installed.')
        return
    state, original, expected, current = loaded
    target = BOOT / 'console.cfg'
    if state['existed']:
        atomic(target, original, state['mode'], state['uid'], state['gid'])
    elif target.exists():
        target.unlink()
    # Restore the console before removing the font it references.
    for name in ('unicode.pf2', 'original.cfg', 'manifest.json'):
        (STATE / name).unlink()
    STATE.rmdir()
    print('Restored the previous GRUB console configuration.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=('install', 'uninstall'))
    parser.add_argument('--dry-run', action='store_true')
    args = parser.parse_args()
    if args.action == 'install' and not supported():
        print('Skipping Dell GRUB console: requires Dell XPS 13 9350, EFI and OSTree.')
        return
    if args.dry_run:
        print(f'Dry run: would {args.action} Dell GRUB graphical console in /boot/grub2; no sudo or writes.')
        return
    if os.geteuid() != 0:
        print(f'Dell XPS 13 9350: {args.action} GRUB graphical console to avoid slow firmware text rendering.\n'
              'Administrator access is required to manage console.cfg, its backup and the font in /boot/grub2.\n'
              'Existing configuration is preserved; kernel arguments and timeout are unchanged. No reboot will occur.\n'
              'The privileged installer checks existing files before making changes.', flush=True)
        subprocess.run(['/usr/bin/sudo', '--', sys.executable, '-I', str(Path(__file__).resolve()), args.action], check=True)
        return
    fd = os.open(LOCK, os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600)
    with os.fdopen(fd, 'w') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        (install if args.action == 'install' else uninstall)()


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, KeyError, RuntimeError, subprocess.CalledProcessError) as error:
        print(f'GRUB console operation failed: {error}', file=sys.stderr)
        sys.exit(1)
