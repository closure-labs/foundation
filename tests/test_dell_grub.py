"""Exercise boot-file ownership and restore behavior without touching real /boot."""
import importlib.util
from pathlib import Path
import os
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location('dell_grub', ROOT / 'modules/hosts/models/dell-xps-9350/_assets/grub-console.py')
grub = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(grub)


class GrubTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        root = Path(self.tmp.name)
        boot = root / 'boot/grub2'
        boot.mkdir(parents=True)
        (boot / 'grub.cfg').write_text('# Generated by bootupd\nsource $prefix/console.cfg\n')
        font = root / 'font.pf2'
        font.write_bytes(b'FILE\x00\x00\x00\x04PFF2fake font')
        self.boot = boot
        for name, value in [('BOOT', boot), ('STATE', boot / 'foundation-dell-grub'), ('FONT', font), ('RECEIPT', root / 'receipt.json')]:
            mock = patch.object(grub, name, value)
            mock.start()
            self.addCleanup(mock.stop)
        # Fixture directories belong to the test user, not root. Production
        # directory validation is exercised separately with mocked stat results.
        self.real_validate = grub.validate_boot
        mock = patch.object(grub, 'receipt_paths', return_value=True)
        mock.start()
        self.addCleanup(mock.stop)
        mock = patch.object(grub, 'validate_boot')
        mock.start()
        self.addCleanup(mock.stop)
        mock = patch.object(grub.os, 'fchown')
        mock.start()
        self.addCleanup(mock.stop)

    def test_install_repeat_and_uninstall_absent_original(self):
        grub.install()
        content = (self.boot / 'console.cfg').read_bytes()
        self.assertIn(b'terminal_output gfxterm', content)
        self.assertNotIn(b'timeout', content)
        grub.install()
        self.assertEqual(content, (self.boot / 'console.cfg').read_bytes())
        grub.uninstall()
        self.assertFalse((self.boot / 'console.cfg').exists())
        grub.uninstall()

    def test_restore_original_bytes_and_mode(self):
        target = self.boot / 'console.cfg'
        target.write_bytes(b'# original without newline')
        target.chmod(0o640)
        grub.install()
        grub.uninstall()
        self.assertEqual(target.read_bytes(), b'# original without newline')
        self.assertEqual(target.stat().st_mode & 0o777, 0o640)

    def test_external_edit_blocks_install_and_uninstall(self):
        grub.install()
        target = self.boot / 'console.cfg'
        target.write_bytes(target.read_bytes() + b'# user edit\n')
        for action in (grub.install, grub.uninstall):
            with self.assertRaisesRegex(RuntimeError, 'changed outside'):
                action()
        self.assertTrue(grub.STATE.exists())

    def test_backup_tampering_blocks_restore(self):
        grub.install()
        (grub.STATE / 'original.cfg').write_bytes(b'changed')
        with self.assertRaisesRegex(RuntimeError, 'backup was modified'):
            grub.uninstall()

    def test_modified_font_blocks_restore(self):
        grub.install()
        (grub.STATE / 'unicode.pf2').write_bytes(b'changed')
        with self.assertRaisesRegex(RuntimeError, 'font changed'):
            grub.uninstall()

    def test_symlink_target_rejected(self):
        target = self.boot / 'console.cfg'
        target.symlink_to(grub.FONT)
        with self.assertRaisesRegex(RuntimeError, 'non-regular'):
            grub.atomic(target, b'bad')
        self.assertTrue(grub.FONT.read_bytes().startswith(b'FILE'))

    def test_incomplete_state_fails_closed(self):
        grub.STATE.mkdir()
        with self.assertRaisesRegex(RuntimeError, 'Incomplete'):
            grub.install()

    def test_interrupted_console_commit_can_resume(self):
        original = grub.atomic
        def fail_console(path, *args, **kwargs):
            if path == self.boot / 'console.cfg':
                raise OSError('simulated interruption')
            return original(path, *args, **kwargs)
        with patch.object(grub, 'atomic', side_effect=fail_console):
            with self.assertRaises(OSError):
                grub.install()
        grub.install()
        grub.uninstall()
        self.assertFalse((self.boot / 'console.cfg').exists())

    def test_dry_run_never_escalates(self):
        with patch.object(grub, 'supported', return_value=True), patch.object(grub.sys, 'argv', ['installer', 'install', '--dry-run']), patch.object(grub.subprocess, 'run') as sudo:
            grub.main()
            sudo.assert_not_called()
        self.assertFalse(grub.STATE.exists())

    def test_unsupported_host_never_escalates(self):
        with patch.object(grub, 'supported', return_value=False), patch.object(grub.sys, 'argv', ['installer', 'install']), patch.object(grub.subprocess, 'run') as sudo:
            grub.main()
            sudo.assert_not_called()

    def test_explanation_precedes_fixed_sudo_command(self):
        events = []
        with patch.object(grub, 'recorded', return_value=False), patch.object(grub, 'supported', return_value=True), patch.object(grub.os, 'geteuid', return_value=1000), patch.object(grub.sys, 'argv', ['installer', 'install']), patch('builtins.print', side_effect=lambda *a, **k: events.append(str(a))), patch.object(grub.subprocess, 'run', side_effect=lambda *a, **k: events.append(a[0])):
            grub.main()
        self.assertIn('Administrator access', events[0])
        self.assertEqual(events[1][:4], ['/usr/bin/sudo', '--', grub.sys.executable, '-I'])
        self.assertEqual(events[1][-1], 'install')

    def test_receipt_skips_sudo_and_boot_inspection(self):
        grub.install()
        with patch.object(grub, 'supported', return_value=True), patch.object(grub.sys, 'argv', ['installer', 'install']), patch.object(grub.subprocess, 'run') as sudo, patch.object(grub, 'validate_boot') as inspect:
            grub.main()
            sudo.assert_not_called()
            inspect.assert_not_called()

    def test_policy_or_machine_change_invalidates_receipt(self):
        grub.install()
        identity = grub.receipt_identity()
        with patch.object(grub, 'receipt_identity', return_value=identity | {'policy': 'new'}):
            self.assertFalse(grub.recorded())
        with patch.object(grub, 'receipt_identity', return_value=identity | {'machine': 'other'}):
            self.assertFalse(grub.recorded())

    def test_uninstall_invalidates_receipt(self):
        grub.install()
        self.assertTrue(grub.recorded())
        grub.uninstall()
        self.assertFalse(grub.recorded())

    def test_untrusted_receipt_never_suppresses_install(self):
        grub.install()
        with patch.object(grub, 'receipt_paths', return_value=False):
            self.assertFalse(grub.recorded())

    def test_explicit_verify_bypasses_receipt_and_checks_boot(self):
        grub.install()
        with patch.object(grub.sys, 'argv', ['installer', 'verify']), patch.object(grub.os, 'geteuid', return_value=0), patch.object(grub.os, 'open', wraps=grub.os.open) as opened:
            # A fixture lock, not the real /run lock.
            with patch.object(grub, 'LOCK', self.boot / 'test.lock'):
                grub.main()
                self.assertTrue(grub.recorded())
                self.assertTrue(opened.called)

    def test_unsafe_boot_directory_rejected(self):
        # On an unprivileged test runner the root ownership check must reject it.
        if os.getuid() != 0:
            with self.assertRaisesRegex(RuntimeError, 'unsafe boot'):
                self.real_validate()


if __name__ == '__main__':
    unittest.main()
